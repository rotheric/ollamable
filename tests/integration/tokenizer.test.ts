// ── AC-TOK-2 ──────────────────────────────────────────────────────────

describe("AC-TOK-2: tokens/tokenIds round-trip via the vocabulary", () => {
  beforeEach(() => mockShow());

  // A naive whole-string single-token split is not satisfiable by this
  // loop either, without a dedicated test (S3-F7 subsumption): such a
  // split would trivially round-trip (tokens=[s]) but fail the
  // vocab-index/byte-decode check below for any fixture-set string that
  // is not itself a single vocab entry — true for the fenced-code-block
  // and literal-pipe fixtures, which the per-index `decodeTokenIds` check
  // below already exercises.
  it.each(FIXTURE_SET)("holds for %s", async (text) => {
    const vocab = await loadVocab(BASE_URL, MODEL);
    const result = tokenizeWithVocab(vocab, text);

    expect(result.tokens).toHaveLength(result.tokenIds.length);
    expect(result.tokens.join("")).toBe(text);

    // tokenIds[i] must be the vocabulary index whose byte-level decoding
    // is tokens[i]. None of the fixture-set strings contain a multi-byte
    // character that a token boundary splits (they're all plain ASCII),
    // so decoding each id INDIVIDUALLY must reproduce tokens[i] exactly —
    // the same claim the streaming decoder makes for the whole sequence,
    // checked here per-index rather than only in aggregate.
    for (let i = 0; i < result.tokenIds.length; i++) {
      expect(decodeTokenIds(vocab, [result.tokenIds[i]])).toEqual([result.tokens[i]]);
    }
  });
});

// ── AC-TOK-3 ──────────────────────────────────────────────────────────

describe("AC-TOK-3: special tokens tokenize as exactly one element each", () => {
  beforeEach(() => mockShow());

  it("<|im_start|> and <|im_end|> each occupy exactly one tokens[] element with the correct id", async () => {
    const vocab = await loadVocab(BASE_URL, MODEL);
    const result = await tokenize(BASE_URL, MODEL, "<|im_start|>Hello<|im_end|>");

    const startIdx = result.tokens.indexOf("<|im_start|>");
    const endIdx = result.tokens.indexOf("<|im_end|>");
    expect(startIdx).toBe(0);
    expect(endIdx).toBe(result.tokens.length - 1);
    expect(result.tokenIds[startIdx]).toBe(vocab.tokenToId.get("<|im_start|>"));
    expect(result.tokenIds[endIdx]).toBe(vocab.tokenToId.get("<|im_end|>"));

    // Not merely "the substring appears somewhere in the joined output" —
    // each special token is its OWN array element, never split.
    expect(result.tokens.filter((t) => t === "<|im_start|>")).toHaveLength(1);
    expect(result.tokens.filter((t) => t === "<|im_end|>")).toHaveLength(1);
  });

  it("matches special tokens ahead of the pre-tokenizer split (adjacent to ordinary text, no separating space)", async () => {
    // If special-token matching ran AFTER the qwen2 split, the regex
    // would instead try to tokenize the literal characters
    // "<|im_start|>" as ordinary punctuation/letter runs.
    const result = await tokenize(BASE_URL, MODEL, "<|im_start|>a|b<|im_end|>");
    expect(result.tokens[0]).toBe("<|im_start|>");
    expect(result.tokens[result.tokens.length - 1]).toBe("<|im_end|>");
  });

  it("also recognizes token_type-classified control tokens that are NOT <|...|>-shaped (S3-C2)", async () => {
    // The fixture's tokenizer.ggml.token_type array marks "<think>" as
    // CONTROL (type 3), same as real Qwen3 GGUF vocabularies — it is not
    // `<|...|>`-shaped, so the shape-based fallback regex alone would
    // split it into ordinary BPE pieces instead of one element. This app
    // is a chat UI for a model that emits "<think>" literally, so this
    // is routine input, not an exotic edge case.
    const vocab = await loadVocab(BASE_URL, MODEL);
    const result = await tokenize(BASE_URL, MODEL, "<think>Hello</think>");

    expect(result.tokens[0]).toBe("<think>");
    expect(result.tokens[result.tokens.length - 1]).toBe("</think>");
    expect(result.tokenIds[0]).toBe(vocab.tokenToId.get("<think>"));
    expect(result.tokenIds[result.tokenIds.length - 1]).toBe(vocab.tokenToId.get("</think>"));
    expect(result.tokens.filter((t) => t === "<think>")).toHaveLength(1);
    expect(result.tokens.filter((t) => t === "</think>")).toHaveLength(1);
  });
});

// ── S3-D2 (fixture-independent): the token_type-absent fallback ─────

describe("S3-D2 (fixture-independent): shape-based special-token fallback when tokenizer.ggml.token_type is absent or malformed", () => {
  // The committed fixture always carries a correctly-sized token_type
  // array, so the AC-TOK-3 suite above only ever exercises the preferred
  // (token_type-driven) branch in buildVocabTable — the shape-regex
  // fallback that runs against any /show response omitting token_type
  // was otherwise untested. This is also the exact branch that
  // reinstates the shape-based detection S3-C2 replaced (that detection
  // was silently wrong for Qwen3's non-`<|...|>`-shaped control tokens),
  // so these tests pin precisely what it does and does not catch rather
  // than asserting it is equivalent to the preferred branch.

  it("still matches <|...|>-shaped tokens as single elements when token_type is absent entirely (the fallback's shape path works)", async () => {
    const mutated = JSON.parse(VOCAB_JSON);
    delete mutated.model_info["tokenizer.ggml.token_type"];
    mockShow(JSON.stringify(mutated));

    const result = await tokenize(BASE_URL, MODEL, "<|im_start|>Hello<|im_end|>");
    expect(result.tokens[0]).toBe("<|im_start|>");
    expect(result.tokens[result.tokens.length - 1]).toBe("<|im_end|>");
    expect(result.tokens.filter((t) => t === "<|im_start|>")).toHaveLength(1);
    expect(result.tokens.filter((t) => t === "<|im_end|>")).toHaveLength(1);
  });

  it("does NOT match a non-<|...|>-shaped control token like <think> when token_type is absent — the fallback's known limitation", async () => {
    const mutated = JSON.parse(VOCAB_JSON);
    delete mutated.model_info["tokenizer.ggml.token_type"];
    mockShow(JSON.stringify(mutated));

    const result = await tokenize(BASE_URL, MODEL, "<think>Hello</think>");
    // Unlike the token_type-driven branch (AC-TOK-3 above), the shape
    // regex only matches `<|...|>`, so "<think>" is run through the
    // ordinary pre-tokenizer/BPE path instead of being kept as one
    // element — this is the documented gap S3-C2 exists to close, and
    // the reason token_type is preferred whenever /show provides it.
    expect(result.tokens.filter((t) => t === "<think>")).toHaveLength(0);
    expect(result.tokens.filter((t) => t === "</think>")).toHaveLength(0);
  });

  it("falls back to shape-based detection when token_type's length doesn't match tokens' length, pinning the length guard", async () => {
    const mutated = JSON.parse(VOCAB_JSON);
    const tokenType: number[] = mutated.model_info["tokenizer.ggml.token_type"];
    // Deliberately truncated — one shorter than tokens[] — so the
    // `tokenType.length === tokens.length` guard in buildVocabTable
    // fails even though the array is present.
    mutated.model_info["tokenizer.ggml.token_type"] = tokenType.slice(0, -1);
    mockShow(JSON.stringify(mutated));

    const result = await tokenize(BASE_URL, MODEL, "<|im_start|>Hello<|im_end|>");
    expect(result.tokens[0]).toBe("<|im_start|>");
    expect(result.tokens[result.tokens.length - 1]).toBe("<|im_end|>");
  });
});

// ── S3-C1 (fixture-independent) ──────────────────────────────────────

describe("S3-C1 (fixture-independent): the real Qwen pre-tokenizer splits every digit into its own pre-token", () => {
  beforeEach(() => mockShow());

  // Deliberately does NOT go through GOLDENS/FIXTURE_SET: those fixtures
  // are hand-built using this same module's own helpers (see the file
  // header), so they cannot falsify anything about the pre-tokenizer
  // itself — a regression back to cl100k_base's `\p{N}{1,3}` digit rule
  // would still satisfy every golden, since none of them contain a
  // digit. This test instead constructs its own vocab mutation and
  // asserts on segmentation shape directly, so it fails against the
  // buggy regex regardless of what the committed fixture happens to say.
  it("never merges adjacent digits, even when the vocab's merge table would otherwise allow it", async () => {
    const mutated = JSON.parse(VOCAB_JSON);
    const tokens: string[] = mutated.model_info["tokenizer.ggml.tokens"];
    const merges: string[] = mutated.model_info["tokenizer.ggml.merges"];

    // "2" and "0" are identity-mapped ASCII in the GPT-2 byte alphabet
    // (byteEncode("2") === "2"), so if the pre-tokenizer ever produced a
    // pre-token containing both digits adjacently (e.g. cl100k_base's
    // `\p{N}{1,3}` grouping "20" into one pre-token), this merge rule
    // would fire and collapse them into a single "20" token. Under the
    // real Qwen `\p{N}` rule, "2" and "0" can never appear in the same
    // pre-token in the first place, so this merge must never have a
    // chance to apply — regardless of what any hand-built golden says.
    if (!tokens.includes("20")) tokens.push("20");
    merges.push("2 0");
    mockShow(JSON.stringify(mutated));

    const result = await tokenize(BASE_URL, MODEL, "2024");
    expect(result.tokens).toEqual(["2", "0", "2", "4"]);
  });
});

// ── S3-C6 / S3-C9 (pre-tokenizer boundary, direct) ───────────────────
//
// These exercise __preTokenizeForTests directly rather than through
// tokenize(): the BPE merge step re-splits every pre-token into
// byte-level symbols unless a merge rule happens to apply, which makes
// pre-token boundaries themselves unobservable through tokenize()'s
// public tokens[] output for arbitrary (non-fixture) input.

describe("S3-C6: case-insensitivity is scoped to the contraction group only", () => {
  it("does not simple-case-fold a combining mark into \\p{L}, unlike a whole-pattern /i flag would", () => {
    // U+0345 COMBINING GREEK YPOGEGRAMMENI case-folds to U+03B9 (ι), a
    // letter — so a whole-pattern `i` flag (with `u`) would make
    // `[^\r\n\p{L}\p{N}]?\p{L}+` treat the combining mark as `\p{L}` and
    // absorb it into the preceding letter run. Precomposed "ᾳ" (U+1FB3)
    // is itself `\p{L}` and stays whole either way; the decomposed form
    // (base letter + combining mark) is the case that discriminates.
    expect(__preTokenizeForTests("ᾳ b")).toEqual(["α", "ͅ", " b"]);
  });
});

describe("S3-C9: whitespace matches Unicode White_Space, not JS's \\s/\\S", () => {
  it("treats U+0085 (NEL) as whitespace, unlike JS's \\s (which excludes it)", () => {
    // JS's \s excludes U+0085 (Next Line); Unicode White_Space includes
    // it. Under \s, two adjacent NELs are ordinary "punctuation" and stay
    // together as one run, with the following letter run split off on
    // its own ("a", "\u0085\u0085", "d"). Under White_Space, the run is
    // whitespace, so the pattern's usual "leave the last space attached
    // to the next word" behavior applies instead ("a", "\u0085",
    // "\u0085d") — a different split, not just a different label.
    expect(__preTokenizeForTests("a\u0085\u0085d")).toEqual(["a", "\u0085", "\u0085d"]);
  });

  it("does not treat U+FEFF (BOM) as whitespace, unlike JS's \\s (which includes it)", () => {
    // Mirror image of the NEL case: JS's \s includes U+FEFF, so two
    // adjacent BOMs would be treated as a whitespace run and split as
    // ("a", "﻿", "﻿d"). Unicode White_Space excludes U+FEFF, so
    // it is ordinary "punctuation" instead and the run stays together:
    // ("a", "﻿﻿", "d").
    expect(__preTokenizeForTests("a﻿﻿d")).toEqual(["a", "﻿﻿", "d"]);
  });
});

// ── AC-PERF-1 / Order-Sensitive Composition Flow 1 ───────────────────

describe("AC-PERF-1: exactly one POST /show per (baseUrl, model), sequential and concurrent", () => {
  it("issues one request across two sequential calls", async () => {
    const fetchSpy = mockShow();
    await tokenize(BASE_URL, MODEL, "Hello world");
    await tokenize(BASE_URL, MODEL, "strawberry");
    expect(fetchSpy).toHaveBeenCalledTimes(1);
  });

  it("issues exactly one request for two calls started concurrently via Promise.all", async () => {
    let resolveShow!: (r: Response) => void;
    const fetchSpy = vi.spyOn(globalThis, "fetch").mockImplementation(
      () => new Promise<Response>((resolve) => { resolveShow = resolve; })
    );

    const p1 = tokenize(BASE_URL, MODEL, "Hello world");
    const p2 = tokenize(BASE_URL, MODEL, "strawberry");
    // Both calls started before the first /show resolves — a cache
    // populated only on resolution would issue two requests here.
    expect(fetchSpy).toHaveBeenCalledTimes(1);

    resolveShow(new Response(VOCAB_JSON, { status: 200 }));
    const [r1, r2] = await Promise.all([p1, p2]);

    expect(fetchSpy).toHaveBeenCalledTimes(1);
    expect(r1.tokenIds).toEqual(GOLDENS["Hello world"]);
    expect(r2.tokenIds).toEqual(GOLDENS["strawberry"]);
  });

  it("issues exactly one request for N=5 concurrent first-calls, and every caller resolves to the same vocab table", async () => {
    let resolveShow!: (r: Response) => void;
    const fetchSpy = vi.spyOn(globalThis, "fetch").mockImplementation(
      () => new Promise<Response>((resolve) => { resolveShow = resolve; })
    );

    const texts = ["Hello world", "strawberry", "Die Verkehrsinfrastruktur", "a|b", "a\n\n\nb"];
    const calls = texts.map((t) => tokenize(BASE_URL, MODEL, t));
    expect(fetchSpy).toHaveBeenCalledTimes(1);

    resolveShow(new Response(VOCAB_JSON, { status: 200 }));
    const results = await Promise.all(calls);

    expect(fetchSpy).toHaveBeenCalledTimes(1);
    results.forEach((r, i) => {
      expect(r.tokenIds).toEqual(GOLDENS[texts[i]]);
    });
  });

  it("a failed load is not cached — the next call retries the fetch", async () => {
    const fetchSpy = vi
      .spyOn(globalThis, "fetch")
      .mockRejectedValueOnce(new Error("network down"))
      .mockResolvedValueOnce(new Response(VOCAB_JSON, { status: 200 }));

    await expect(tokenize(BASE_URL, MODEL, "hi")).rejects.toThrow();
    const result = await tokenize(BASE_URL, MODEL, "Hello world");

    expect(fetchSpy).toHaveBeenCalledTimes(2);
    expect(result.tokenIds).toEqual(GOLDENS["Hello world"]);
  });

  it("never evicts an in-flight entry, even when the bounded LRU is exceeded (S3-R2)", async () => {
    const resolvers: Array<(r: Response) => void> = [];
    const fetchSpy = vi.spyOn(globalThis, "fetch").mockImplementation(
      () => new Promise<Response>((resolve) => { resolvers.push(resolve); })
    );

    const MODEL_A = "model-a";
    const MODEL_B = "model-b";
    const MODEL_C = "model-c";
    const MODEL_D = "model-d";

    // A and B are loaded and settle immediately — A is the oldest entry
    // once C and D are added below.
    const pA = loadVocab(BASE_URL, MODEL_A);
    resolvers[0](new Response(VOCAB_JSON, { status: 200 }));
    await pA;

    const pB = loadVocab(BASE_URL, MODEL_B);
    resolvers[1](new Response(VOCAB_JSON, { status: 200 }));
    await pB;

    // C is started but deliberately left in flight — its /show never
    // resolves until later in this test.
    const pC = loadVocab(BASE_URL, MODEL_C);
    expect(fetchSpy).toHaveBeenCalledTimes(3);

    // D pushes the cache to size 4 (> VOCAB_CACHE_MAX_ENTRIES=3),
    // triggering eviction. The naive "evict the oldest key" policy would
    // evict C here, even though it is still in flight (S3-R2). The fix
    // must instead evict A: the oldest entry that has actually SETTLED.
    const pD = loadVocab(BASE_URL, MODEL_D);
    resolvers[3](new Response(VOCAB_JSON, { status: 200 }));
    await pD;

    // Only now does C's original /show resolve.
    resolvers[2](new Response(VOCAB_JSON, { status: 200 }));
    await pC;

    // A second call for C must attach to the very entry that survived
    // eviction — no new /show — proving it was never dropped while in
    // flight.
    await loadVocab(BASE_URL, MODEL_C);
    expect(fetchSpy).toHaveBeenCalledTimes(4);

    // A, by contrast, was legitimately evicted (it had already settled),
    // so calling it again correctly issues a fresh /show.
    const pA2 = loadVocab(BASE_URL, MODEL_A);
    expect(fetchSpy).toHaveBeenCalledTimes(5);
    resolvers[4](new Response(VOCAB_JSON, { status: 200 }));
    await pA2;
  });
});

