// ── AC-TOK-6: property test over arbitrary well-formed unicode ───────

describe("AC-TOK-6: tokens.join('') === s for arbitrary well-formed unicode", () => {
  beforeEach(() => mockShow());

  it("holds for fc.string({unit: 'binary'}) — full Unicode scalar range, no lone surrogates", async () => {
    await fc.assert(
      fc.asyncProperty(
        fc.string({ unit: "binary", maxLength: 60 }),
        async (s) => {
          const result = await tokenize(BASE_URL, MODEL, s);
          expect(result.tokens.join("")).toBe(s);
          expect(result.tokens).toHaveLength(result.tokenIds.length);
        }
      ),
      { numRuns: 300 }
    );
  });

  it("holds for the empty string and length-1 strings", async () => {
    const empty = await tokenize(BASE_URL, MODEL, "");
    expect(empty.tokens).toEqual([]);
    expect(empty.tokenIds).toEqual([]);

    for (const ch of ["a", " ", "\n", "😀", "|"]) {
      const result = await tokenize(BASE_URL, MODEL, ch);
      expect(result.tokens.join("")).toBe(ch);
    }
  });

  it("holds for a leading BOM (U+FEFF) — TextDecoder must not strip it", async () => {
    const s = "﻿hello";
    const result = await tokenize(BASE_URL, MODEL, s);
    expect(result.tokens.join("")).toBe(s);
  });

  it("holds for mixed scripts, emoji, and consecutive-whitespace runs", async () => {
    const samples = ["héllo wörld", "日本語テスト", "a😀😀b", "a     b", "line1\n\n\nline2", "\t\t  \n"];
    for (const s of samples) {
      const result = await tokenize(BASE_URL, MODEL, s);
      expect(result.tokens.join("")).toBe(s);
    }
  });
});
